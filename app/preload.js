const { contextBridge, ipcRenderer } = require("electron");
contextBridge.exposeInMainWorld("pet", {
  preferences: () => ipcRenderer.invoke('pet-preferences'),
  onPreferences: fn => ipcRenderer.on('pet-preferences', (_e, value) => fn(value)),
  onConnection: fn => ipcRenderer.on('connection-state', (_e, value) => fn(value)),
  companionDisconnect: () => ipcRenderer.invoke('companion-disconnect'),
  ignoreMouse: (v) => ipcRenderer.send("ignore-mouse", v),
  dragStart: (off) => ipcRenderer.send("drag-start", off),
  dragEnd: () => ipcRenderer.send("drag-end"),
  onDragMove: (fn) => ipcRenderer.on("drag-move", (_e, d) => fn(d)),
  onState: (fn) => ipcRenderer.on("state", (_e, s) => fn(s)),
  onEasterEgg: fn => ipcRenderer.on('easter-egg', (_e, value) => fn(value)),
  onSay: (fn) => ipcRenderer.on("say", (_e, k) => fn(k)),
  onMute: (fn) => ipcRenderer.on("mute", (_e, v) => fn(v)),
  bounds: () => ipcRenderer.invoke("bounds"),
  moveTo: (x, y) => ipcRenderer.send("move-to", { x, y }),
  menu: () => ipcRenderer.send("menu"),
  onCompanion: (fn) => ipcRenderer.on('companion-update', (_e, value) => fn(value)),
  companionImport: () => ipcRenderer.invoke('companion-import'),
  companionConfig: () => ipcRenderer.invoke('companion-config'),
  companionSave: (input) => ipcRenderer.invoke('companion-save', input),
  companionSend: (data) => ipcRenderer.invoke('companion-send', data),
  companionTest: () => ipcRenderer.invoke('companion-test'),
  quit: () => ipcRenderer.send("quit"),
});
